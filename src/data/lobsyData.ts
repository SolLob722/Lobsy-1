export function getPagesForEdition(edition: ArchiveEdition): RestoredPage[] {
  const folder = ARCHIVE_EDITIONS[edition].folder;
  const list: RestoredPage[] = BASE_PAGE_TEMPLATES.map((item) => ({
    slug: item.slug,
    title: item.title,
    path: `/${folder}/${item.file}`,
    category: item.category,
    description: item.description,
    timestamp: item.timestamp,
    badge: item.badge,
  }));

  if (edition === 'lobsy2') {
    list.push({
      slug: 'snapshot_20220817032451_verbatim.html',
      title: 'Verbatim 2022 Snapshot (Raw Archive)',
      path: `/${folder}/snapshot_20220817032451_verbatim.html`,
      category: 'snapshot',
      description: 'Raw HTML preserved exactly as captured by Wayback Machine on August 17, 2022.',
      timestamp: '2022-08-17 03:24:51',
      badge: 'Raw Archive',
    });
  } else {
    list.push(
      {
        slug: 'snapshot_20230304112228_clean.html',
        title: 'Verbatim Snapshot 2023/03/04 (Cleaned Crash State)',
        path: `/${folder}/snapshot_20230304112228_clean.html`,
        category: 'snapshot',
        description: 'The exact snapshot captured on 2023-03-04 with Wayback code stripped, showing the WordPress 500 error.',
        timestamp: '2023-03-04 11:22:28',
        badge: 'Diagnostic',
      },
      {
        slug: 'snapshot_20230304112228_verbatim.html',
        title: 'Verbatim Snapshot 2023/03/04 (Raw Archive)',
        path: `/${folder}/snapshot_20230304112228_verbatim.html`,
        category: 'snapshot',
        description: 'Raw HTML preserved exactly as captured by Wayback Machine on March 4, 2023.',
        timestamp: '2023-03-04 11:22:28',
        badge: 'Raw Archive',
      }
    );
  }

  return list;
}

